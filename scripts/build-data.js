#!/usr/bin/env node
/* Build src/data/pdx-data.js from ODK CSV submissions.
   Usage:
     node scripts/build-data.js           validate + write src/data/pdx-data.js
     node scripts/build-data.js --check   validate only (exit 1 on errors), used in pull requests
   No npm dependencies. Requires Node 18+. */
'use strict';
const fs = require('fs');
const path = require('path');
const { parseCsv, buildHazard } = require('./build-core');

const ROOT = path.resolve(__dirname, '..');
const D = p => path.join(ROOT, 'data', p);
const check = process.argv.includes('--check');
const readJson = p => JSON.parse(fs.readFileSync(p, 'utf8'));
const readCsv = p => parseCsv(fs.readFileSync(p, 'utf8'));

const hazards = readJson(D('config/hazards.json'));
const countries = readJson(D('config/countries.json'));
const out = {}, report = [];
let totalErrors = 0;

for (const id of Object.keys(hazards)) {
  const cfg = hazards[id];
  const qFile = D(`questions/${id}.csv`);
  if (!fs.existsSync(qFile)) { console.error(`✖ ${id}: missing ${path.relative(ROOT, qFile)}`); totalErrors++; continue; }
  const subDir = D(`submissions/${id}`);
  const names = fs.existsSync(subDir) ? fs.readdirSync(subDir).filter(f => f.toLowerCase().endsWith('.csv')).sort() : [];
  const files = names.map(n => ({ name: `submissions/${id}/${n}`, ...readCsv(path.join(subDir, n)) }));
  const curFile = D(`curated/${id}.json`);
  const curated = fs.existsSync(curFile) ? readJson(curFile) : {};
  const r = buildHazard(cfg, countries, readCsv(qFile).records, files, curated);
  out[id] = r.hazard;
  totalErrors += r.errors.length;

  report.push(`## ${cfg.name}`, '',
    `- Submission files: ${r.stats.files}`,
    `- Rows read / used: ${r.stats.rowsRead} / ${r.stats.rowsUsed}`,
    `- Countries: ${r.stats.countries} · Country assessments: ${r.stats.assessments}`,
    `- Rounds: ${r.stats.rounds.join(', ') || '—'}`,
    `- Errors: ${r.errors.length} · Warnings: ${r.warnings.length}`, '');
  if (r.errors.length) report.push('### Errors', ...r.errors.slice(0, 200).map(e => `- ${e}`), '');
  if (r.warnings.length) report.push('### Warnings', ...r.warnings.slice(0, 200).map(w => `- ${w}`), '');

  console.log(`${r.errors.length ? '✖' : '✔'} ${cfg.name}: ${r.stats.countries} countries, ${r.stats.assessments} assessments, ${r.errors.length} errors, ${r.warnings.length} warnings`);
  r.errors.slice(0, 50).forEach(e => console.error('  error   ' + e));
  r.warnings.slice(0, 20).forEach(w => console.warn('  warning ' + w));
}

fs.mkdirSync(D('build'), { recursive: true });
fs.writeFileSync(D('build/validation-report.md'), `# Data validation report\n\nGenerated ${new Date().toISOString()}\n\n` + report.join('\n') + '\n');

if (totalErrors) { console.error(`\n${totalErrors} error(s). Fix the CSVs listed above; src/data/pdx-data.js was not updated.`); process.exit(1); }
if (check) { console.log('\nValidation passed (check mode, nothing written).'); process.exit(0); }

const meta = { generated: new Date().toISOString(), hazards: Object.fromEntries(Object.entries(out).map(([k, h]) => [k, { rounds: h.rounds, countries: h.countries.length }])) };
const js = '/* GENERATED by scripts/build-data.js. Do not edit by hand; edit data/ and rebuild. */\n'
  + 'window.PDX_META=' + JSON.stringify(meta) + ';\n'
  + 'window.PDX_DATA=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(ROOT, 'src/data/pdx-data.js'), js);
console.log(`\nWrote src/data/pdx-data.js (${(js.length / 1024).toFixed(0)} KB).`);
